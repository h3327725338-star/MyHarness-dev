#!/usr/bin/env node
/**
 * Builds the Android app.
 *
 *   node packages/mobile/build.mjs            the page only: fills android/app/src/main/assets/www
 *   node packages/mobile/build.mjs --apk      the page, then the signed release APK into packages/mobile/dist
 *   node packages/mobile/build.mjs --debug    the page, then a debug APK (inspectable page, separate signature)
 *
 * The page is the phone UI (`web/`), the desktop Web UI files it shares (`shared-files.mjs`) and the agent core
 * (`src/core.ts`) bundled for a browser. Only the APK steps need Java and the Android SDK; see README.md.
 */

import { spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { build } from "esbuild";
import { coreEntry, mobileDir, oauthAppsFile, promptFiles, sharedFiles, webDir, wwwDir } from "./shared-files.mjs";

const args = new Set(process.argv.slice(2));
const wantApk = args.has("--apk");
const wantDebug = args.has("--debug");

const pkg = JSON.parse(readFileSync(join(mobileDir, "package.json"), "utf8"));

/** Android needs a whole number that grows with every release: 0.0.8 → 8, 1.2.3 → 10203. */
export function versionCode(version) {
	const [major = 0, minor = 0, patch = 0] = String(version).split(".").map((part) => Number.parseInt(part, 10) || 0);
	return major * 10000 + minor * 100 + patch;
}

/** The embedded prompt texts as one module, so the page never needs the files themselves. */
export function promptsModule() {
	const out = {};
	for (const [name, file] of Object.entries(promptFiles())) out[name] = readFileSync(file, "utf8").trim();
	return `// Generated by build.mjs from system-prompts/. Edit the .md files, not this file.\nexport const PROMPTS = ${JSON.stringify(out, null, "\t")};\n`;
}

/**
 * The Google OAuth app the phone signs in with: the desktop's own (oauth-apps.ts), read at build time so the page
 * sources hold no copy of it. `MYHARNESS_GOOGLE_CLIENT_ID` / `MYHARNESS_GOOGLE_CLIENT_SECRET` build with another app.
 * Like the desktop's, the secret of an installed app is not a confidential value (see oauth-apps.ts).
 */
export function googleOAuthModule() {
	let clientId = (process.env.MYHARNESS_GOOGLE_CLIENT_ID || "").trim();
	let clientSecret = (process.env.MYHARNESS_GOOGLE_CLIENT_SECRET || "").trim();
	if (!clientId) {
		const block = /\bgoogle:\s*\{([\s\S]*?)\}/.exec(readFileSync(oauthAppsFile, "utf8"))?.[1] || "";
		clientId = /clientId:\s*"([^"]*)"/.exec(block)?.[1] || "";
		clientSecret = /clientSecret:\s*"([^"]*)"/.exec(block)?.[1] || "";
	}
	return `// Generated by build.mjs from packages/coding-agent/src/providers/credentials/oauth-apps.ts.
export const GOOGLE_OAUTH = ${JSON.stringify({ clientId, clientSecret })};
`;
}

export async function bundleCore(outfile) {
	await build({
		entryPoints: [coreEntry],
		bundle: true,
		format: "esm",
		platform: "browser",
		target: "es2022",
		outfile,
		minify: true,
		legalComments: "none",
		logLevel: "warning",
		define: { "process.env.NODE_ENV": '"production"' },
	});
}

async function buildWeb() {
	rmSync(wwwDir, { recursive: true, force: true });
	mkdirSync(wwwDir, { recursive: true });
	cpSync(webDir, wwwDir, { recursive: true });
	for (const [target, source] of sharedFiles()) {
		const to = join(wwwDir, target);
		mkdirSync(dirname(to), { recursive: true });
		cpSync(source, to);
	}
	writeFileSync(join(wwwDir, "js", "prompts.generated.js"), promptsModule());
	writeFileSync(join(wwwDir, "js", "oauth.generated.js"), googleOAuthModule());
	await bundleCore(join(wwwDir, "js", "core.bundle.js"));
	writeFileSync(
		join(wwwDir, "build-info.json"),
		`${JSON.stringify({ version: pkg.version, versionCode: versionCode(pkg.version), builtAt: new Date().toISOString() }, null, "\t")}\n`,
	);
	console.log(`Page written to ${wwwDir}`);
}

/** Where Java and the Android SDK are: the environment's own setting, or the folder README.md describes. */
function toolchain() {
	const local = join(process.env.LOCALAPPDATA || join(homedir(), "AppData", "Local"), "MyHarnessAndroid");
	const javaHome = process.env.JAVA_HOME || join(local, "jdk");
	const androidHome = process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT || join(local, "sdk");
	if (!existsSync(join(javaHome, "bin")) || !existsSync(join(androidHome, "platforms")))
		throw new Error(
			`Java or the Android SDK was not found (looked at ${javaHome} and ${androidHome}). Set JAVA_HOME and ANDROID_HOME, or see packages/mobile/README.md.`,
		);
	const env = { ...process.env, JAVA_HOME: javaHome, ANDROID_HOME: androidHome, ANDROID_SDK_ROOT: androidHome };
	// A toolchain kept in the README's folder keeps its caches there too, so removing that folder removes everything.
	if (existsSync(local) && !process.env.GRADLE_USER_HOME) env.GRADLE_USER_HOME = join(local, "gradle-home");
	if (existsSync(local) && !process.env.ANDROID_USER_HOME) env.ANDROID_USER_HOME = join(local, "android-home");
	return { env, javaHome };
}

/**
 * The key that signs release APKs. Android only installs an update over an app signed with the same key, so the key
 * is made once and kept with the user's MyHarness data, outside the repository. Losing it means uninstalling the app
 * (and its chats) before a newer build can be installed.
 */
function signingProperties({ env, javaHome }) {
	const dir = process.env.MYHARNESS_ANDROID_SIGNING_DIR || join(homedir(), ".myharness", "android-signing");
	const propertiesFile = join(dir, "signing.properties");
	if (existsSync(propertiesFile)) return propertiesFile;
	mkdirSync(dir, { recursive: true });
	const storeFile = join(dir, "myharness-release.jks");
	const password = randomBytes(24).toString("base64url");
	const keytool = join(javaHome, "bin", process.platform === "win32" ? "keytool.exe" : "keytool");
	const made = spawnSync(
		keytool,
		["-genkeypair", "-keystore", storeFile, "-storetype", "PKCS12", "-storepass:env", "MH_STOREPASS", "-alias", "myharness", "-keyalg", "RSA", "-keysize", "3072", "-validity", "18250", "-dname", "CN=MyHarness"],
		{ env: { ...env, MH_STOREPASS: password }, encoding: "utf8" },
	);
	if (made.status !== 0) throw new Error(`Could not create the signing key: ${made.stderr || made.stdout}`);
	const escaped = storeFile.replace(/\\/g, "/");
	writeFileSync(propertiesFile, `storeFile=${escaped}\nstorePassword=${password}\nkeyAlias=myharness\nkeyPassword=${password}\n`);
	console.log(`Created the release signing key in ${dir}. Keep this folder: updates must be signed with the same key.`);
	return propertiesFile;
}

function buildApk(debug) {
	const tools = toolchain();
	const androidDir = join(mobileDir, "android");
	const gradle = join(androidDir, process.platform === "win32" ? "gradlew.bat" : "gradlew");
	const gradleArgs = [
		debug ? "assembleDebug" : "assembleRelease",
		"--no-daemon",
		"-q",
		`-PmyharnessVersionName=${pkg.version}`,
		`-PmyharnessVersionCode=${versionCode(pkg.version)}`,
	];
	if (!debug) gradleArgs.push(`-PmyharnessSigningProperties=${signingProperties(tools).replace(/\\/g, "/")}`);
	const run = spawnSync(gradle, gradleArgs, { cwd: androidDir, env: tools.env, stdio: "inherit", shell: process.platform === "win32" });
	if (run.status !== 0) throw new Error(`Gradle failed (exit ${run.status}).`);
	const kind = debug ? "debug" : "release";
	const built = join(androidDir, "app", "build", "outputs", "apk", kind, `app-${kind}.apk`);
	if (!existsSync(built)) throw new Error(`Gradle finished but ${built} is missing.`);
	const dist = join(mobileDir, "dist");
	mkdirSync(dist, { recursive: true });
	const target = join(dist, `MyHarness-${pkg.version}${debug ? "-debug" : ""}.apk`);
	cpSync(built, target);
	console.log(`APK written to ${target}`);
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, "/").split("/").pop())) {
	try {
		await buildWeb();
		if (wantApk || wantDebug) buildApk(wantDebug);
	} catch (error) {
		console.error(error instanceof Error ? error.message : error);
		process.exit(1);
	}
}
